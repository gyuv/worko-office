/** Regenerates src/publicapi/openapi.public.ts from docs/openapi.yaml (operations tagged `public`). Run after editing the spec. */
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';
import { publicSpec } from '../src/publicapi/public-spec.js';

const spec = parse(readFileSync(new URL('../../../docs/openapi.yaml', import.meta.url), 'utf8'));
const out = `// GENERATED by scripts/gen-public-openapi.ts from docs/openapi.yaml — do not edit.\nexport const PUBLIC_OPENAPI = ${JSON.stringify(publicSpec(spec), null, 2)} as const;\n`;
writeFileSync(new URL('../src/publicapi/openapi.public.ts', import.meta.url), out);
console.log(`public spec: ${Object.keys(publicSpec(spec).paths).length} paths`);
